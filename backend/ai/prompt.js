'use strict';

const { ENTITY_TYPES, ENTITY_TYPE_CODES, FORM_ENTITY_TYPE_CODES, SCREEN_TARGETS, SCREEN_CODES } = require('./tools');

/**
 * Системный промпт ИИ-архитектора (issue #78, docs/ai-architect.md §6.2).
 * Промпт собирается на сервере: модель никогда не получает SQL и не решает, что можно читать.
 */

function entityCatalog(allowedTypes) {
  const types = ENTITY_TYPE_CODES.filter((t) => !allowedTypes || allowedTypes.includes(t));
  return types
    .map((t) => {
      const meta = ENTITY_TYPES[t];
      const form = meta.form && FORM_ENTITY_TYPE_CODES.includes(t) ? 'есть форма UI' : 'только чтение (формы нет)';
      // Поля черновика берём из белого списка инструмента — промпт и валидация не расходятся.
      const prefill = meta.prefillFields && meta.prefillFields.length
        ? `; предзаполнение (prefill_form): ${meta.prefillFields.join(', ')}`
        : '';
      return `- ${t} — ${meta.plural} (${form}${prefill})`;
    })
    .join('\n');
}

/**
 * Экраны вне реестров (аналитика/дашборды/радар). ИИ их только открывает: данные «Анализа зависимостей»
 * он получает инструментом `get_relations` (рёбра метамодели), поэтому в промпте перечисляем существование
 * разделов явно — иначе модель отрицает реальную функциональность ИСАР.
 */
function screenCatalog() {
  return Object.entries(SCREEN_TARGETS)
    .map(([code, meta]) => {
      const focus = meta.focus ? '; поддерживает фокус графа (focusEntityType + focusIds)' : '';
      return `- ${code} — ${meta.plural} (${meta.listPath}; право ${meta.readPermission}; данных не отдаёт, доступен только переход${focus})`;
    })
    .join('\n');
}

/**
 * Перечень экранов одной строкой для правил промпта: `analytics («Анализ зависимостей»), dashboards («Дашборды»), …`.
 * Строится из `SCREEN_TARGETS`, поэтому добавление экрана не требует правки текста правил.
 */
function screenHint() {
  return SCREEN_CODES.map((code) => {
    const plural = SCREEN_TARGETS[code].plural;
    return plural && plural !== code ? `${code} («${plural}»)` : code;
  }).join(', ');
}

